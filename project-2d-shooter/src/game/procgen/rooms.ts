/**
 * Hand-made room templates, assembled procedurally (the Dead Cells / Spelunky approach:
 * authored rooms keep quality, procedural layout keeps variety).
 *
 * Every template is ROOM_COLS x ROOM_ROWS characters:
 *   #  solid      =  one-way platform      .  empty
 *   P  player spawn candidate   X  exit candidate   E  enemy spawn
 *   C  crate   B  explosive barrel   D  door (bottom tile; 3 tall)
 *   L  hanging lamp (falls when shot)   F  fire extinguisher (smoke when shot)
 *
 * Authoring rules (the generator carves these areas when it connects rooms):
 *   - border rows/cols are solid;
 *   - side doors: rows 12-15 next to the left/right walls (no props there);
 *   - vertical shaft: cols 13-16, full height.
 */
